        createdAt = createdAt,
        updatedAt = updatedAt,
        lastOpenedAt = lastOpenedAt,
        isFavorite = isFavorite,
        isPinned = isPinned,
        isArchived = isArchived,
        isDeleted = isDeleted,
        processingStatus = processingStatus,
        userNote = userNote,
        captureNote = captureNote,
        entities = entities,
        tags = tags,
        collections = collections
    )

    private fun parseCommentsJson(json: String?): List<SavedComment> {
        if (json.isNullOrBlank()) return emptyList()
        return try {
            val array = org.json.JSONArray(json)
            val list = mutableListOf<SavedComment>()
            for (i in 0 until array.length()) {
                val obj = array.getJSONObject(i)
                val text = obj.optString("text", "")
                if (text.isNotBlank()) {
                    list.add(
                        SavedComment(
                            author = obj.optString("author", "User"),
                            text = text,
                            score = if (obj.has("score")) obj.optInt("score") else null,
                            timestamp = if (obj.has("timestamp")) obj.optLong("timestamp") else null
                        )
                    )
                }
            }
            list
        } catch (e: Exception) {
            emptyList()
        }
    }
}
