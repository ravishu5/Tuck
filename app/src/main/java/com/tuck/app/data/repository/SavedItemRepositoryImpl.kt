@Singleton
class SavedItemRepositoryImpl @Inject constructor(
    private val savedItemDao: SavedItemDao,
    private val savedItemFtsDao: SavedItemFtsDao,
    private val entityDao: EntityDao,
    private val tagDao: TagDao,
    private val collectionDao: CollectionDao,
    private val fileStorageService: FileStorageService
) : SavedItemRepository {

    override fun getAllActiveItems(): Flow<List<SavedItem>> {
        return savedItemDao.getAllActiveItems().map { list ->
            list.map { it.toDomain() }
        }
    }

    override fun getRecentItems(limit: Int): Flow<List<SavedItem>> {
        return savedItemDao.getRecentItems(limit).map { list ->
            list.map { it.toDomain() }
        }
    }

    override fun getFavoriteItems(): Flow<List<SavedItem>> {
        return savedItemDao.getFavoriteItems().map { list ->
            list.map { it.toDomain() }
        }
    }

    override fun getArchivedItems(): Flow<List<SavedItem>> {
        return savedItemDao.getArchivedItems().map { list ->
            list.map { it.toDomain() }
        }
    }

    override fun getTrashedItems(): Flow<List<SavedItem>> {
        return savedItemDao.getTrashedItems().map { list ->
            list.map { it.toDomain() }
        }
    }

    override fun getItemsByType(contentType: ContentType): Flow<List<SavedItem>> {
        return savedItemDao.getItemsByType(contentType).map { list ->
            list.map { it.toDomain() }
        }
    }

    override fun getItemsByCollection(collectionId: Long): Flow<List<SavedItem>> {
        return savedItemDao.getItemsByCollection(collectionId).map { list ->
            list.map { it.toDomain() }
        }
    }

    override fun getItemByIdFlow(id: Long): Flow<SavedItem?> {
        return savedItemDao.getItemByIdFlow(id).map { entity ->
            entity?.let { loadFullItem(it) }
        }
    }

    override suspend fun getItemById(id: Long): SavedItem? = withContext(Dispatchers.IO) {
        val entity = savedItemDao.getItemById(id) ?: return@withContext null
        loadFullItem(entity)
    }

    private suspend fun loadFullItem(entity: SavedItemEntity): SavedItem {
        val entities = entityDao.getEntitiesForItem(entity.id).map {
            ExtractedEntity(
                id = it.id,
                savedItemId = it.savedItemId,
                type = it.type,
                value = it.value,
                normalizedValue = it.normalizedValue
            )
        }
        val tags = tagDao.getTagsForSavedItem(entity.id).map {
            Tag(id = it.id, name = it.name)
        }
        val collections = collectionDao.getCollectionsForSavedItem(entity.id).map {
            Collection(
                id = it.id,
                name = it.name,
                isAutoGenerated = it.isAutoGenerated,
                icon = it.icon,
                createdAt = it.createdAt
            )
        }
        return entity.toDomain(entities = entities, tags = tags, collections = collections)
    }

    override suspend fun insertItem(item: SavedItem): Long = withContext(Dispatchers.IO) {
        val entity = SavedItemEntity(
            id = item.id,
            contentType = item.contentType,
            title = item.title,
            description = item.description,
            originalUrl = item.originalUrl,
            canonicalUrl = item.canonicalUrl,
            sourceDomain = item.sourceDomain,
            sourceApp = item.sourceApp,
            mimeType = item.mimeType,
            localFilePath = item.localFilePath,
            thumbnailPath = item.thumbnailPath,
            originalText = item.originalText,
            extractedText = item.extractedText,
            ocrText = item.ocrText,
            createdAt = item.createdAt,
            updatedAt = item.updatedAt,
            lastOpenedAt = item.lastOpenedAt,
            isFavorite = item.isFavorite,
            isPinned = item.isPinned,
            isArchived = item.isArchived,
            isDeleted = item.isDeleted,
            processingStatus = item.processingStatus,
            userNote = item.userNote,
            captureNote = item.captureNote
        )
        val generatedId = savedItemDao.insert(entity)

        // Seed initial FTS entry
        val fts = SavedItemFtsEntity(
            rowid = generatedId,
            title = item.title,
            description = item.description.orEmpty(),
            originalUrl = item.originalUrl.orEmpty(),
            sourceDomain = item.sourceDomain.orEmpty(),
            originalText = item.originalText.orEmpty(),
            extractedText = item.extractedText.orEmpty(),
            ocrText = item.ocrText.orEmpty(),
            tags = "",
            entities = ""
        )
        savedItemFtsDao.insertOrUpdate(fts)

        generatedId
    }

    override suspend fun updateItem(item: SavedItem): Unit = withContext(Dispatchers.IO) {
        val entity = SavedItemEntity(
            id = item.id,
            contentType = item.contentType,
            title = item.title,
            description = item.description,
            originalUrl = item.originalUrl,
            canonicalUrl = item.canonicalUrl,
            sourceDomain = item.sourceDomain,
            sourceApp = item.sourceApp,
            mimeType = item.mimeType,
            localFilePath = item.localFilePath,
            thumbnailPath = item.thumbnailPath,
            originalText = item.originalText,
            extractedText = item.extractedText,
            ocrText = item.ocrText,
            createdAt = item.createdAt,
            updatedAt = System.currentTimeMillis(),
            lastOpenedAt = item.lastOpenedAt,
            isFavorite = item.isFavorite,
            isPinned = item.isPinned,
            isArchived = item.isArchived,
            isDeleted = item.isDeleted,
            processingStatus = item.processingStatus,
            userNote = item.userNote,
            captureNote = item.captureNote
        )
        savedItemDao.update(entity)

        val fts = SavedItemFtsEntity(
            rowid = item.id,
            title = item.title,
            description = item.description.orEmpty(),
            originalUrl = item.originalUrl.orEmpty(),
            sourceDomain = item.sourceDomain.orEmpty(),
            originalText = item.originalText.orEmpty(),
            extractedText = item.extractedText.orEmpty(),
            ocrText = item.ocrText.orEmpty(),
            tags = item.tags.joinToString(" ") { it.name },
            entities = item.entities.joinToString(" ") { it.value }
        )
        savedItemFtsDao.insertOrUpdate(fts)
    }

    override suspend fun updateProcessingStatus(
        id: Long,
        status: ProcessingStatus,
        ocrText: String?,
        extractedText: String?,
        title: String?,
        description: String?
    ) = withContext(Dispatchers.IO) {
        savedItemDao.updateProcessingResult(
            id = id,
            status = status,
            ocrText = ocrText,
            extractedText = extractedText,
            title = title,
            description = description
        )
    }

    override suspend fun setFavorite(id: Long, isFavorite: Boolean) = withContext(Dispatchers.IO) {
        savedItemDao.setFavorite(id, isFavorite)
    }

    override suspend fun setArchived(id: Long, isArchived: Boolean) = withContext(Dispatchers.IO) {
        savedItemDao.setArchived(id, isArchived)
    }

    override suspend fun moveToTrash(id: Long) = withContext(Dispatchers.IO) {
        savedItemDao.moveToTrash(id)
    }

    override suspend fun restoreFromTrash(id: Long) = withContext(Dispatchers.IO) {
        savedItemDao.restoreFromTrash(id)
    }

    override suspend fun permanentlyDelete(id: Long) = withContext(Dispatchers.IO) {
        val item = savedItemDao.getItemById(id)
        if (item != null) {
            fileStorageService.deleteFile(item.localFilePath)
            fileStorageService.deleteFile(item.thumbnailPath)
            savedItemFtsDao.delete(id)
            savedItemDao.permanentlyDelete(id)
        }
    }

    override suspend fun emptyTrash() = withContext(Dispatchers.IO) {
        val trashedItems = savedItemDao.getTrashedItemsList()
        for (item in trashedItems) {
            fileStorageService.deleteFile(item.localFilePath)
            fileStorageService.deleteFile(item.thumbnailPath)
            savedItemFtsDao.delete(item.id)
        }
        savedItemDao.emptyTrash()
        Unit
    }

    override suspend fun markOpened(id: Long) = withContext(Dispatchers.IO) {
        savedItemDao.updateLastOpened(id)
    }

    override suspend fun findByCanonicalUrl(canonicalUrl: String): SavedItem? = withContext(Dispatchers.IO) {
        savedItemDao.findByCanonicalUrl(canonicalUrl)?.toDomain()
    }

    override suspend fun findByTextHash(hash: String): SavedItem? = withContext(Dispatchers.IO) {
        savedItemDao.findByTextHash(hash)?.toDomain()
    }

    override suspend fun findByImageHash(sha256: String): SavedItem? = withContext(Dispatchers.IO) {
        savedItemDao.findByImageHash(sha256)?.toDomain()
    }

    override suspend fun addItemToCollection(itemId: Long, collectionId: Long) = withContext(Dispatchers.IO) {
        collectionDao.insertItemCollectionCrossRef(
            SavedItemCollectionCrossRef(savedItemId = itemId, collectionId = collectionId)
        )
    }

    override suspend fun removeItemFromCollection(itemId: Long, collectionId: Long) = withContext(Dispatchers.IO) {
        collectionDao.removeItemFromCollection(savedItemId = itemId, collectionId = collectionId)
    }

    override suspend fun setItemCollections(itemId: Long, collectionIds: List<Long>) = withContext(Dispatchers.IO) {
        collectionDao.clearCollectionsForSavedItem(itemId)
        for (cId in collectionIds) {
            collectionDao.insertItemCollectionCrossRef(
                SavedItemCollectionCrossRef(savedItemId = itemId, collectionId = cId)
            )
        }
    }

